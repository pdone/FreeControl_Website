import fs from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkIconVersions, ROOT } from './sync-assets.mjs';

const read = (file) => fs.readFileSync(file, 'utf8');
const toKebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2').toLowerCase();
const toPascal = (name) => name.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('');

function svelteFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const file = join(dir, entry.name);
    return entry.isDirectory() ? svelteFiles(file) : entry.isFile() && entry.name.endsWith('.svelte') ? [file] : [];
  });
}

export function collectIconNames(root = ROOT) {
  const names = new Set();
  const collect = (text, pattern) => {
    for (const [, name] of text.matchAll(pattern)) if (/^[A-Z][A-Za-z0-9]*$/.test(name)) names.add(toKebab(name));
  };
  for (const file of svelteFiles(join(root, 'src'))) {
    const source = read(file);
    collect(source, /<Icon\s+name="([^"]+)"/g);
    const dynamic = source.match(/const NEXT_ICON[^=]*=\s*\{([^}]+)\}/)?.[1] ?? '';
    collect(dynamic, /:\s*'([^']+)'/g);
  }
  collect(read(join(root, 'src/lib/i18n.ts')), /\bicon:\s*'([^']+)'/g);
  return [...names].sort();
}

export function generateIcons({ root = ROOT, check = false } = {}) {
  const version = checkIconVersions(root, { generated: check });
  const names = collectIconNames(root);
  const lines = names.map((name) => {
    const file = join(root, 'node_modules/lucide-svelte/dist/icons', `${name}.svelte`);
    const literal = read(file).match(/const iconNode = (\[[\s\S]*?\]);/)?.[1];
    if (!literal) throw new Error(`Missing iconNode JSON: ${name}`);
    return `  ${toPascal(name)}: ${JSON.stringify(['svg', {}, JSON.parse(literal)])},`;
  });
  const file = join(root, 'src/lib/icon-set.ts');
  const previous = fs.existsSync(file) ? read(file) : '';
  const eol = previous.includes('\r\n') ? '\r\n' : '\n';
  const output = [
    '// Generated by scripts/gen-icon-subset.mjs; lucide-svelte (ISC), see public/LICENSE.lucide.',
    'export type IconNode = [string, Record<string, string | number>, IconNode[]?];',
    '',
    `export const LUCIDE_VERSION = '${version}';`,
    '',
    'export const ICONS: Record<string, IconNode> = {',
    ...lines,
    '};',
    '',
  ].join(eol);
  if (check) {
    if (previous.replace(/\r\n/g, '\n') !== output.replace(/\r\n/g, '\n')) throw new Error('src/lib/icon-set.ts differs from website references; run npm run icons:ui');
  } else {
    fs.mkdirSync(dirname(file), { recursive: true });
    fs.writeFileSync(file, output);
  }
  return { count: names.length, version };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length && args[0] !== '--check')) throw new Error('Usage: npm run icons:ui | npm run check:icons');
    const result = generateIcons({ check: args[0] === '--check' });
    console.log(`[icons] ${result.count} website icons, lucide-svelte@${result.version}`);
  } catch (error) { console.error(`[icons] ${error.message}`); process.exitCode = 1; }
}
